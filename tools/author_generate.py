#!/usr/bin/env python3
"""G12 — generate the existing content/src/*.ch lesson shape from one JSON file.

A non-agent author edits ONE structured concept file and runs this generator.
The emitted file uses #html/#css/#js macros (no string-built markup), escapes
all authored text and attribute values, and carries the source_ref of every
unit. The pilot is `elf/bytes`; generated output is NOT swapped into the served
course — it is previewed locally by author_preview.py and lint-checked.
"""
import argparse
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
from author_lint import check  # noqa: E402


def chemical_text(value):
    """Escape authored text for literal use inside an #html macro body."""
    out = html.escape(str(value), quote=True)
    return out.replace('{', '&#123;').replace('}', '&#125;')


def render_ch(spec):
    fn = spec['concept_id'].replace('-', '_') + '_pilot'
    lines = [
        '// GENERATED by tools/author_generate.py — edit the structured file, not this output.',
        '// Source: content/authoring/%s/%s.json' % (spec['course'], spec['concept_id']),
        'import page',
        'import html_cbi',
        'import css_cbi',
        'import js_cbi',
        '',
        'public namespace underlayer_content {',
        '',
        '    public func render_%s() : string {' % fn,
        '        var page = HtmlPage()',
        '        page.defaultPrepare()',
        '        #html {',
        '            <div class="lesson authored-lesson">',
        '                <h1>%s</h1>' % chemical_text(spec['title']),
        '                <p class="authored-objective">%s</p>' % chemical_text(spec['objective']),
    ]
    for unit in spec['units']:
        lines.append('                <section class="unit unit-%s" data-source-ref="%s:%s">' % (
            chemical_text(unit['kind']), chemical_text(spec['source_ref']),
            chemical_text(unit['source_line'])))
        lines.append('                    <h2>%s</h2>' % chemical_text(unit['heading']))
        lines.append('                    <p>%s</p>' % chemical_text(unit['text']))
        lines.append('                </section>')
    key = spec['answer_key']
    lines.append('                <p class="authored-takeaway">%s</p>' % chemical_text(spec['takeaway']))
    lines.append('                <div class="quiz" data-source-ref="%s">' % chemical_text(key['source_ref']))
    lines.append('                    <h2>%s</h2>' % chemical_text(key['question']))
    for i, option in enumerate(key['options']):
        marker = 'true' if i == key['correct_index'] else 'false'
        lines.append('                    <button type="button" class="quiz-option" data-correct="%s" data-explain="%s">%s</button>' % (
            marker, chemical_text(key['explanation']), chemical_text(option)))
    lines += [
        '                    <p class="quiz-feedback" role="status"></p>',
        '                </div>',
        '            </div>',
        '        }',
        '        #css {',
        '            .authored-lesson { max-width: 68ch; margin: 0 auto; padding: 2rem 1.5rem; }',
        '            .authored-objective { font-weight: 600; color: hsl(var(--primary)); }',
        '            .authored-takeaway { margin-top: 1.5rem; font-weight: 600; }',
        '            .unit { margin: 1rem 0; padding: 1rem; border: 1px solid hsl(var(--border)); border-radius: 8px; }',
        '            .quiz-option { display: block; width: 100%; min-height: 2.75rem; margin: 0.5rem 0; cursor: pointer; }',
        '        }',
        '        #js {',
        "            document.querySelectorAll('.quiz-option').forEach(function(b) {",
        '                b.addEventListener("click", function() {',
        '                    var box = b.parentElement.querySelector(".quiz-feedback");',
        '                    if(box) { box.textContent = b.getAttribute("data-explain"); }',
        '                });',
        '            });',
        '        }',
        '        return page.toString()',
        '    }',
        '',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('file', nargs='?',
                    default='content/authoring/elf/bytes.json')
    ap.add_argument('--check', action='store_true', help='lint only, do not write')
    args = ap.parse_args()
    path = Path(args.file)
    if not path.is_absolute():
        path = ROOT / path
    spec = json.loads(path.read_text(encoding='utf-8'))
    problems = check(spec)
    if problems:
        for item in problems:
            print('FAIL ' + item)
        return 1
    out = (ROOT / 'content/authoring/generated' / spec['course'] /
           (spec['concept_id'] + '.ch'))
    text = render_ch(spec)
    print('AUTHOR GENERATE lint: 0 failure(s)')
    print('output: %s (%d bytes)' % (out.relative_to(ROOT), len(text)))
    if not args.check:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding='utf-8')
        print('written: %s' % out.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
